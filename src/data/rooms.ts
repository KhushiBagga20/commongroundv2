export interface RawThread {
  id: string
  roomId: string
  authorId: string
  tag: 'question' | 'show & tell' | 'idea' | 'help' | 'chat'
  title: string
  body: string
  hoursAgo: number
  replies: [authorId: string, body: string][]
}

export interface RawProject {
  id: string
  roomId: string
  makerId: string
  title: string
  blurb: string
  cover: { pattern: PatternId; bg: string; fg: string; art: string }
  lookingForCollab: boolean
  daysAgo: number
}

export interface RawHappening {
  id: string
  roomId: string
  title: string
  inDays: number
  hour: number
  where: string
  kind: 'online' | 'irl'
  blurb: string
  capacity: number
  going: number
}

export interface RawQuest {
  id: string
  roomId: string
  code: string
  title: string
  brief: string
}

